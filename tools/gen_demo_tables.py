#!/usr/bin/env python3
"""Generate the pure-Rust demo-encoding tables (Phase 1).

The demo writer must run without the engine (`cargo test` on the host), so the
two wire tables are embedded in `rust/src/demo/fields.rs`:

  * `ENTITY_FIELDS` — the shipped server's `netField_t entityStateFields[]`
    (132 entries; i386 `netField_t` is 12 bytes, field offset at +4, bit width
    at +8, terminator none). The source-tree table is stale (113 entries); see
    docs/demo-format.md §8.
  * `HUFFMAN_CODES` — the 256 static `msg_hData` Huffman codes. `MSG_WriteBits`
    encodes whole bytes as symbols of that tree; the tree is preloaded once and
    never adapted per message (docs/demo-format.md §2).

Run from the repository root:

    python3 tools/gen_demo_tables.py > /tmp/opencode/demo-tables.rs

The output is pasted into `rust/src/demo/fields.rs` (kept as a generated
constant with this header). Regenerate after a Phase 0 re-pin.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "runtime"))

import demo_inspect as di  # noqa: E402
import jka_proto as jp  # noqa: E402

ENTITY_FIELDS_ADDR = 0x081A15A0
ENTITY_FIELDS_COUNT = 132


def huffman_codes():
    """Walk the static msg_hData tree and return (code, len) per symbol.

    The bit order matches huffman.cpp `send()`: root-to-leaf, LSB-first in the
    output byte (`Huff_putBit`), so `code` bit 0 is the first transmitted bit.
    """
    h = jp._init_tree()
    for i in range(256):
        for _ in range(jp.MSG_HDATA[i]):
            h.add_ref(i)
    out = []
    for ch in range(256):
        node = h.loc[ch]
        chain = []
        child = None
        while node is not None:
            chain.append((node, child))
            child = node
            node = node.parent
        code = 0
        nbits = 0
        for cur, chd in reversed(chain):
            if chd is not None:
                if cur.right is chd:
                    code |= 1 << nbits
                nbits += 1
        out.append((code, nbits))
    return out


def main():
    binary = di.Binary(di.ENGINE)
    fields = binary.netfields(ENTITY_FIELDS_ADDR, ENTITY_FIELDS_COUNT)
    codes = huffman_codes()

    print("// GENERATED by tools/gen_demo_tables.py — do not hand-edit.")
    print("//")
    print("// ENTITY_FIELDS: shipped linuxjampded 1.011 entityStateFields[]")
    print(f"// at 0x{ENTITY_FIELDS_ADDR:08x} ({ENTITY_FIELDS_COUNT} entries, 12 bytes each).")
    print("// HUFFMAN_CODES: static msg_hData tree; bit 0 = first transmitted bit.")
    print()
    print(f"pub(crate) const ENTITY_FIELDS: [(u16, i8); {len(fields)}] = [")
    for i, (ofs, bits) in enumerate(fields):
        if not -128 <= bits <= 127:
            raise SystemExit(f"field {i}: bits {bits} does not fit i8")
        print(f"    ({ofs}, {bits}),")
    print("];")
    print()
    print(f"pub(crate) const HUFFMAN_CODES: [(u16, u8); {len(codes)}] = [")
    for i, (code, nbits) in enumerate(codes):
        if code > 0xFFFF:
            raise SystemExit(f"symbol {i}: code does not fit u16")
        print(f"    (0x{code:04x}, {nbits}),")
    print("];")


if __name__ == "__main__":
    main()
